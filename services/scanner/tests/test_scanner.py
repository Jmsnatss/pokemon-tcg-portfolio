"""Scanner service test suite."""
import pytest
from fastapi.testclient import TestClient
from app.main import app

client = TestClient(app)


def test_health_check():
    """Health endpoint should return 200 with status ok."""
    response = client.get("/health")
    assert response.status_code == 200
    data = response.json()
    assert data["status"] == "ok"
    assert data["service"] == "pokevault-scanner"
    assert "providers" in data


def test_scan_unsupported_format():
    """Non-image MIME types should be rejected with 415."""
    response = client.post(
        "/scan",
        files={"file": ("test.txt", b"not an image", "text/plain")},
    )
    assert response.status_code == 415


def test_scan_too_large():
    """Images over 10 MB should be rejected with 413."""
    large_bytes = b"x" * (10 * 1024 * 1024 + 1)
    response = client.post(
        "/scan",
        files={"file": ("big.jpg", large_bytes, "image/jpeg")},
    )
    assert response.status_code == 413


